"""Render docs/benchmarks/comparison.md from measured benchmark JSON.

Input: the ``--json`` output of ``scripts/bench_exact.py`` (run with
``--full --matrix --categorical`` for the complete page), and optionally the
``--json`` output of ``scripts/bench_vs_competitors.py``. The page is
generated, never hand-edited: numbers appear on it only if a measured run
produced them, stamped with the machine and versions that measured them.

Run: ``uv run python docs/scripts/benchmarks.py --exact-json results.json``
"""

from __future__ import annotations

import argparse
import json
import pathlib

REPO = pathlib.Path(__file__).resolve().parents[2]
OUT = REPO / "docs" / "benchmarks" / "comparison.md"

POSITIONING = """\
## Positioning

How treecf's approach relates to the other families of counterfactual
methods for tree ensembles:

| Family | Representatives | Optimality | Constraints | Verified output | Extra dependency |
|---|---|---|---|---|---|
| Tree-native search (this library) | treecf | proof, certified infeasibility, certified regions | declarative, compiled for every backend | float-verified against the parsed model, always | none — numpy plus the bundled core |
| Model-agnostic perturbation | DiCE (genetic/random/kdtree) | none | post-hoc penalty terms | not re-verified by default | none |
| Nearest-neighbor greedy | NICE | none | none | validity checked, cost not minimized | none |
| MILP over the ensemble | OCEAN-style formulations | proof, given a solver | linear, in the MILP | exact within the encoding | commercial or heavyweight MILP solver |
| Counterfactual maps / gradient methods | alibi CounterfactualProto | none | none | gradient-based; struggles on non-differentiable ensembles | TensorFlow |

Measured head-to-head numbers against the pip-installable competitors
(per-instance wall time, validity, plan cost) are in
[Backends — against other CF libraries](../concepts/backends.md#against-other-cf-libraries);
they come from `scripts/bench_vs_competitors.py` under one shared protocol.
"""


def _fmt_s(value: float) -> str:
    return f"{value:.3f} s"


def _scenario_rows(results: list[dict]) -> str:
    lines = [
        "| Scenario | genetic median | exact (warm) median | exact (cold) median "
        "| heuristic gap median | proof mix |",
        "|---|---|---|---|---|---|",
    ]
    for r in results:
        if r.get("kind") == "certification":
            continue
        proof_mix = ", ".join(f"{k}: {v}" for k, v in r["proof_mix"].items())
        lines.append(
            f"| {r['tag']} | {_fmt_s(r['genetic'][0])} | {_fmt_s(r['exact_warm'][0])} "
            f"| {_fmt_s(r['exact_cold'][0])} | {r['gap_median']:.2%} | {proof_mix} |"
        )
    return "\n".join(lines)


def _certification_rows(results: list[dict], prefix: str) -> str:
    rows = [
        r
        for r in results
        if r.get("kind") == "certification" and str(r["tag"]).startswith(prefix)
    ]
    if not rows:
        return ""
    lines = [
        "| Scenario | time-to-certificate median | certified ≤ 10 s | certified ≤ 60 s |",
        "|---|---|---|---|",
    ]
    for r in rows:
        median = r["median_time_to_certificate_s"]
        median_cell = _fmt_s(median) if median == median else "—"
        lines.append(
            f"| {r['tag'].removeprefix(prefix).strip()} "
            f"| {median_cell} "
            f"| {r['certified_within_10s']:.0%} | {r['certified_within_60s']:.0%} |"
        )
    lines.append("")
    lines.append("A dash: no seed certified within the 60 s budget on this machine.")
    return "\n".join(lines)


def render(exact: dict, competitors: list[dict] | None) -> str:
    stamp = exact["stamp"]
    results = exact["results"]
    versions = ", ".join(
        f"{lib} {stamp[lib]}" for lib in ("xgboost", "lightgbm") if stamp.get(lib)
    )
    parts = [
        "# Benchmarks",
        "",
        "This page is generated by `docs/scripts/benchmarks.py` from the JSON",
        "output of `scripts/bench_exact.py` — every number below was measured,",
        "on the machine stamped here, by a run anyone can repeat.",
        "",
        f"**Measured on:** {stamp['system']} {stamp['machine']}, "
        f"{stamp['cpu_count']} cores, Python {stamp['python']}, "
        f"treecf {stamp['treecf']}, {versions}. The exact engine is "
        "sequential; wall times are per solve.",
        "",
        "## Exact versus genetic",
        "",
        "Same model, same target, same seeds; the genetic backend's *gap* is how",
        "much plan cost the heuristic leaves on the table relative to the proved",
        "optimum. Per-solve budgets: 5 s wall, 2,000,000 nodes.",
        "",
        _scenario_rows(results),
    ]
    matrix = _certification_rows(results, "matrix")
    if matrix:
        parts += [
            "",
            "## Time to certificate, by model scale",
            "",
            "Each cell asks for a *certified* answer — proved optimal, optimal",
            "within gap, or certified infeasible — with a 60 s wall budget and an",
            "effectively unlimited node budget.",
            "",
            matrix,
        ]
    categorical = _certification_rows(results, "categorical")
    if categorical:
        parts += [
            "",
            "## Native categorical models",
            "",
            "LightGBM models with four numeric levers plus native categorical",
            "features of cardinality 3, 8, and 15 — the search runs over",
            "[category blocks](../concepts/categorical.md#category-blocks), so",
            "cardinality is not the cost driver.",
            "",
            categorical,
        ]
    parts += ["", POSITIONING.rstrip()]
    if competitors:
        parts += [
            "",
            "Competitor JSON was supplied for this render; per-scenario details",
            "remain in the backends chapter, generated from the same file.",
        ]
    parts += [
        "",
        "Reproduce: `uv run python scripts/bench_exact.py --full --matrix "
        "--categorical --json results.json`, then re-run this generator.",
        "",
    ]
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--exact-json", required=True, help="scripts/bench_exact.py --json output")
    parser.add_argument(
        "--competitors-json", default=None, help="scripts/bench_vs_competitors.py --json output"
    )
    args = parser.parse_args()

    exact = json.loads(pathlib.Path(args.exact_json).read_text(encoding="utf-8"))
    competitors = None
    if args.competitors_json:
        competitors = json.loads(pathlib.Path(args.competitors_json).read_text(encoding="utf-8"))
    OUT.write_text(render(exact, competitors), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
